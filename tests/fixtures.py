"""Small reproducible validation fixture (synthetic; no real footage).

    python tests/fixtures.py /tmp/ff-fixture

creates two "camera" sources with duplicate basenames, a path with spaces, a
non-video file, and a corrupt clip, all generated by FFmpeg's lavfi test sources.
"""
import subprocess
import sys
from pathlib import Path


def make_clip(path, seconds=1, size='320x240', pattern='testsrc2', codec='mpeg4'):
    path.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i',
                    f'{pattern}=size={size}:rate=24', '-t', str(seconds), '-c:v', codec,
                    str(path)], check=True)
    return path


def make_fixture(root):
    root = Path(root)
    cam_a, cam_b = root / 'Camera A', root / 'Camera B'
    make_clip(cam_a / 'DCIM' / 'C0001.mp4')
    make_clip(cam_a / 'DCIM' / 'clip with spaces.mov', pattern='smptebars')
    make_clip(cam_b / 'DCIM' / 'C0001.mp4', pattern='mandelbrot')
    (cam_b / 'DCIM' / 'C0002.mp4').write_bytes(b'not really a video')  # corrupt
    (cam_b / 'notes.txt').write_text('ignored: not a video extension')
    return cam_a, cam_b


if __name__ == '__main__':
    for path in make_fixture(sys.argv[1]):
        print(path)
